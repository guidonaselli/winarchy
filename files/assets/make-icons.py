"""Generates src/icons.rs from the Phosphor Duotone SVGs in assets/phosphor-src (MIT, see LICENSE there)."""
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
source = os.path.join(here, "phosphor-src")
names = sorted(f[:-4] for f in os.listdir(source) if f.endswith(".svg"))


def variant(name):
    return "".join(part.capitalize() for part in name.split("-"))


out = ["// Generated by assets/make-icons.py from Phosphor Icons (MIT). Do not edit by hand.", ""]
out.append("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n#[allow(dead_code)]\npub enum Icon {")
out += [f"    {variant(n)}," for n in names]
out.append("}\n")
out.append("// (path data on a 256x256 grid, is the translucent accent layer)")
out.append("pub fn layers(icon: Icon) -> &'static [(&'static str, bool)] {\n    match icon {")
for n in names:
    text = open(os.path.join(source, n + ".svg"), encoding="utf-8").read()
    paths = re.findall(r'<path d="([^"]+)"( opacity="0\.2")?/>', text)
    assert paths, n
    body = ", ".join(f'("{d}", {"true" if tint else "false"})' for d, tint in paths)
    out.append(f"        Icon::{variant(n)} => &[{body}],")
out.append("    }\n}\n")
open(os.path.join(here, "..", "src", "icons.rs"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(len(names), "icons")
